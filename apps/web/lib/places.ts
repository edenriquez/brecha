export type PlaceState = { cve: string; name: string; ring: number[]; bbox: Area };

function bboxOf(ring: number[]): Area {
  const lngs = ring.filter((_, i) => i % 2 === 0);
  const lats = ring.filter((_, i) => i % 2 === 1);
  return [Math.min(...lngs), Math.min(...lats), Math.max(...lngs), Math.max(...lats)];
}

export const STATES: PlaceState[] = STATE_RINGS.map(([cve, name, ring]) => ({ cve, name, ring, bbox: bboxOf(ring) })).sort((a, b) =>
  a.name.localeCompare(b.name),
);

export function findState(code: string | null) {
  return STATES.find((s) => s.cve === code) ?? null;
}

/** Punto en polígono por cruce de rayos. */
function inRing({ lat, lng }: { lat: number; lng: number }, ring: number[]) {
  let inside = false;
  for (let i = 0, j = ring.length - 2; i < ring.length; j = i, i += 2) {
    const [xi, yi, xj, yj] = [ring[i], ring[i + 1], ring[j], ring[j + 1]];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** Con un estado elegido cuenta su límite y no su caja: la de Estado de México envuelve a la Ciudad de México. */
export function inPlace(point: { lat: number; lng: number }, area: Area, code: string | null) {
  const state = findState(code);
  return state ? inRing(point, state.ring) : inArea(point, area);
}

/** Valor de `lugar` cuando la zona sale de la ubicación del navegador. */
export const MY_LOCATION = "gps";

/** Zona alrededor de tu ubicación: 15 km a cada lado. */
export function areaAround(position: { lat: number; lng: number }) {
  return formatArea(boxAround([position], 15));
}

/**
 * `lugar` guarda la clave del estado o "gps"; cualquier otra (como las de municipio de enlaces viejos) no nombra
 * nada. `label` va en la píldora y el chip; `where`, en frases ("rutas cerca de…").
 */
export function describePlace(code: string | null): { label: string; where: string } | null {
  if (code === MY_LOCATION) return { label: "Cerca de ti", where: "cerca de ti" };
  const state = findState(code);
  return state && { label: `Todo ${state.name}`, where: `en ${state.name}` };
}

/** Estados cuyo nombre contiene el texto, sin acentos ni mayúsculas. */
export function searchStates(text: string) {
  const q = normalize(text);
  return STATES.filter((s) => normalize(s.name).includes(q));
}
